class Personality:


    def __init__(self):


        # 身份系统

        self.identity = Identity()



    # =========================
    # 取某个字段：
    # 用户自定义优先，否则用默认
    # =========================

    def _field(self, key):


        value = (self.identity.get(key) or "").strip()

        # 旧版 user_profile.json 里
        # 自带一句简短简介，会把新的完整
        # 默认设定挡在后面，
        # 视作"未自定义"处理。
        #
        # 这个字符串原本写死在函数里，
        # 设置页要判断"当前是默认还是自定义"
        # 就得再抄一遍 —— 提出来共用。

        if value and value != (
            LEGACY_PERSONALITY
        ):

            return value


        return DEFAULTS.get(key, "")



    def introduce(self):


        name = self.identity.get(
            "echo_name"
        )

        if not name:

            name = "Soulmate"


